import type { Metadata } from 'next';
import { cache } from 'react';
import { notFound, permanentRedirect } from 'next/navigation';
import { getTeamBySlug } from '@/lib/data';
import { siteTodayYmd } from '@/lib/site-today';
import { isPromoPagesLive, loadPromoPageContext, resolvePreviousSlug, resolvePromoPage, type PromoPage, type PromoPageContext } from '@/lib/promo-pages';
import { promoPagePath } from '@/lib/promo-page-copy';
import { PromoPageView, heroImage, promoPageHead } from '@/components/promo-page/PromoPageView';
import { storedImageSize, type ImageSize } from '@/lib/image-dimensions';

// Per-promo pages (Phase 3b, 2026-10-29): /{league}/{team}/promos/{pageSlug}.
//
// ISR WITH BLOCKING FALLBACK (spec Lifecycle). No path is prerendered: every
// page renders on its first request, is cached, and is regenerated by the
// pipeline's post-write revalidate or after a day, so a promo written by a
// scan has a page before any ping. That is generateStaticParams returning
// nothing with dynamicParams left on.
//
// THE FLAG. PROMO_PAGES_LIVE unset or not "true": the route is a 404, for
// every path, before any read. Nothing links here until the flag is on
// (inbound anchors stay on the team pages this phase) and the sitemap lists
// nothing, so the family does not exist for a crawler until the switch.
//
// RESOLUTION. The slug's rows for this team, the current season's group
// winning (src/lib/promo-pages.ts resolvePromoPage). A slug no row carries
// but some row lists in previousSlugs (the slug re-mint of 2026-10-29) is a
// permanent redirect to that row's current slug (or to that page's canonical
// when it is a duplicate, one hop); a slug no row knows is a
// 404. A slug whose every row is tombstoned renders the removed page; a row
// with no usable date or name renders with noindex (brief A.5).

export const revalidate = 86400;
export const dynamicParams = true;

export async function generateStaticParams(): Promise<{ sport: string; team: string; slug: string }[]> {
  return [];
}

type Params = Promise<{ sport: string; team: string; slug: string }>;

// The route's ONE clock read per request: the instant, and from it the site's
// day (America/New_York), shared by generateMetadata and the body through
// React's request cache, so the noindex decision and the page cannot
// straddle Eastern midnight. The instant itself reaches the view for the date
// tile's state line, which is read in the venue's zone (content floor,
// 2026-11-07); it is the same read, not a second one.
const nowForRequest = cache(() => new Date());
const todayForRequest = cache(() => siteTodayYmd(nowForRequest()));

type Resolved = { kind: 'page'; page: PromoPage; ctx: PromoPageContext; today: string; now: Date; imageSize: ImageSize | null } | { kind: 'redirect'; to: string } | null;

async function resolve(params: Params): Promise<Resolved> {
  const { sport, team: teamSlug, slug } = await params;
  const team = await getTeamBySlug(teamSlug);
  if (!team || team.sportSlug !== sport) return null;
  const today = todayForRequest();
  const page = await resolvePromoPage(team, slug, today);
  if (!page) {
    // An old slug: the page body answers with the redirect (the metadata of
    // a redirected response is never read).
    const current = await resolvePreviousSlug(team, slug);
    if (!current) return null;
    // ONE HOP (ruling 2026-11-10): when the row's current page is itself a
    // duplicate under the canonical rule, the old slug goes straight to the
    // canonical, not to a page that would point a crawler on again
    // (d-a-de-los-muertos was 308 to -2026-27, which canonicals to -night).
    const currentPage = await resolvePromoPage(team, current, today);
    return { kind: 'redirect', to: promoPagePath(sport, team.id, currentPage?.canonicalSlug ?? current) };
  }
  const ctx = await loadPromoPageContext(page, today);
  // The hero's width and height: the card's are fixed, a stored photo's are
  // read from its own header (src/lib/image-dimensions.ts), once per request.
  const hero = heroImage(page);
  const imageSize = hero.kind === 'photo' ? await storedImageSize(hero.url) : null;
  return { kind: 'page', page, ctx, today, now: nowForRequest(), imageSize };
}

export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  if (!isPromoPagesLive()) return {};
  const r = await resolve(params);
  if (!r || r.kind === 'redirect') return {};
  const head = promoPageHead(r.page, r.ctx, r.today, r.imageSize);
  // An absolute title (a package page whose team would not fit with the
  // suffix, ruling 2026-11-10) is the whole <title>: no " | PromoNight".
  const socialTitle = head.titleAbsolute ? head.title : `${head.title} | PromoNight`;
  return {
    // Bare: the root layout's title.template appends " | PromoNight".
    title: head.titleAbsolute ? { absolute: head.title } : head.title,
    description: head.description,
    alternates: { canonical: head.canonical },
    // A complete openGraph, never a partial one: the root's would otherwise be
    // inherited wholesale and og:url would be the homepage (src/lib/og.ts).
    // The image is the share card (2026-11-03), on every variant (single,
    // series, played, removed); the Event schema keeps the tier image.
    openGraph: {
      type: 'website',
      siteName: 'PromoNight',
      url: head.canonical,
      title: socialTitle,
      description: head.description,
      images: [{ url: head.shareCard.url, width: head.shareCard.width, height: head.shareCard.height, alt: head.shareCard.alt }],
    },
    twitter: {
      card: 'summary_large_image',
      site: '@promo_night_app',
      creator: '@promo_night_app',
      title: socialTitle,
      description: head.description,
      images: [{ url: head.shareCard.url, alt: head.shareCard.alt }],
    },
    robots: head.indexable ? undefined : { index: false, follow: true },
  };
}

export default async function PromoPage({ params }: { params: Params }) {
  if (!isPromoPagesLive()) notFound();
  const r = await resolve(params);
  if (!r) notFound();
  // 308, the permanent redirect the App Router issues (a 301 is not
  // available to a page); search engines treat the two alike.
  if (r.kind === 'redirect') permanentRedirect(r.to);
  return <PromoPageView page={r.page} ctx={r.ctx} today={r.today} now={r.now} imageSize={r.imageSize} />;
}
