import type { Metadata } from 'next';
import { cache } from 'react';
import { notFound, permanentRedirect } from 'next/navigation';
import { EventStopView, eventStopHead } from '@/components/events/EventStopView';
import { getUpcomingStopSummaries, resolveEventStop } from '@/lib/events/event-stops';
import { resolveTenantTeamLinks } from '@/lib/venue-hub';
import { eventStopPath, isEventsPagesLive } from '@/lib/events/event-pages';

// /events/{show}/{venue} (Phase 2, 2026-11-18): one evergreen page per stop.
//
// ISR WITH BLOCKING FALLBACK, like the promo pages: nothing is prerendered,
// each page renders on its first request and is regenerated by the pipeline's
// revalidate, the nightly refresh, or after an hour. An hour, not a day: a
// performance loses its ticket button by the clock, and the page a visitor is
// served must not be showing a button for a show that started this afternoon.
//
// THE FLAG. EVENTS_PAGES_LIVE unset or not "true": a 404 for every path,
// before any read. RESOLUTION: the stop whose pageSlug is the segment and
// whose venue hub clears the floor; a slug some stop lists in previousSlugs
// is a 308 to that stop's current slug; anything else is a 404. A tombstoned
// stop renders its removed page with noindex (the per-promo rule).
export const revalidate = 3600;
export const dynamicParams = true;
export async function generateStaticParams(): Promise<{ show: string; venue: string }[]> {
  return [];
}

type Params = Promise<{ show: string; venue: string }>;
// ONE clock read per request, shared by the head and the body.
const nowForRequest = cache(() => new Date());

export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  if (!isEventsPagesLive()) return {};
  const { show, venue } = await params;
  const r = await resolveEventStop(show, venue);
  if (!r || r.kind === 'redirect') return {};
  const head = eventStopHead(r.page.stop, r.page.hub, r.page.floor, nowForRequest());
  const socialTitle = `${head.title} | PromoNight`;
  return {
    title: head.title,
    description: head.description,
    alternates: { canonical: head.canonical },
    openGraph: { type: 'website', siteName: 'PromoNight', url: head.canonical, title: socialTitle, description: head.description, images: [{ url: head.card.url, width: head.card.width, height: head.card.height, alt: head.card.alt }] },
    twitter: { card: 'summary_large_image', site: '@promo_night_app', creator: '@promo_night_app', title: socialTitle, description: head.description, images: [{ url: head.card.url, alt: head.card.alt }] },
    robots: head.indexable ? undefined : { index: false, follow: true },
  };
}

export default async function EventStopPage({ params }: { params: Params }) {
  if (!isEventsPagesLive()) notFound();
  const { show, venue } = await params;
  const r = await resolveEventStop(show, venue);
  if (!r) notFound();
  if (r.kind === 'redirect') permanentRedirect(eventStopPath(show, r.to));
  const now = nowForRequest();
  const { stop, hub, floor } = r.page;
  const [teams, all] = await Promise.all([resolveTenantTeamLinks(hub), getUpcomingStopSummaries(stop.show, now)]);
  return <EventStopView stop={stop} hub={hub} floor={floor} now={now} teams={teams} otherStops={all.filter((s) => s.venueSlug !== stop.venueSlug)} />;
}
