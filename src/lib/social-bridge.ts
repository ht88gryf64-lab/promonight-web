// The social bridge (2026-11-05): the short links the video pipeline
// (promo-video, feature/hooks-v3) prints on its Shorts and Reels, and the
// bio links of the PromoNight social profiles, resolved to the site's own
// pages.
//
//   getpromonight.com/{teamShort}          the end card's "Full details" line
//   getpromonight.com/p/{code}?utm_...     the META caption's promo link and
//                                          the TikTok bio link
//   getpromonight.com/yt /tt /ig /fb       the profile bio links: the
//                                          homepage, tagged by platform
//
// THE TEAM AND BIO LINKS are answered in the middleware (src/middleware.ts,
// shortLinkRedirect below): a 307 that keeps the query string, carries
// X-Robots-Tag: noindex, and never reaches a page or the request counter (a
// hop is not a visit; the destination is counted). src/config/social-bridge.json
// maps each team slug to its team page (/{league}/{teamId}) or school page
// (/cfb/{schoolId}). The file is GENERATED by the pipeline (`npm run
// export-social-bridge` in promo-video) from its config/team-short.json and
// the Firestore team docs; it is never edited here, and the source test
// (src/lib/__tests__/social-bridge-source.test.ts) fails when it is stale.
//
// THE PROMO LINK is resolved at request time (src/app/p/[code]/route.ts):
// `code` is the first six characters of the promo's 16-hex Firestore id and
// utm_content carries the whole id. The route looks the code up in the
// upcoming promo index (every visible promo dated today or later with a page
// slug, the read the promo pages already hold) and redirects to the promo
// page; the whole id in utm_content settles a prefix shared by two promos. A
// code that matches nothing upcoming (the game is over, the promo was pulled,
// the pages are switched off) goes to /promos/today rather than a 404: the
// link is in a caption that stays up after the game.
//
// NONE of these are pages: no sitemap entry, every response noindex
// (src/lib/__tests__/social-bridge.test.ts pins both).
//
// Pure and client-safe: no clock, no Firestore, no env.

import bridge from '../config/social-bridge.json';
import { withQuery } from './url-query';

/** A short link's slug: 2 to 14 lowercase letters or digits (promo-video src/lib/team-short.ts TEAM_SHORT_PATTERN). */
export const TEAM_SHORT_RE = /^[a-z0-9]{2,14}$/;
/** The first six characters of a 16-hex promo id. */
export const PROMO_CODE_RE = /^[a-f0-9]{6}$/i;
/** A whole promo id, as utm_content carries it. */
export const PROMO_ID_RE = /^[a-f0-9]{16}$/i;
/** Where a promo link lands when its code resolves to nothing upcoming. */
export const PROMO_FALLBACK_PATH = '/promos/today';
/** The header every short-link response carries. */
export const NOINDEX_HEADER = { 'x-robots-tag': 'noindex' } as const;

/** The profile bio links: slug to utm_source. All land on the homepage with
 *  utm_medium=social and utm_campaign=bio. */
export const BIO_LINKS: Readonly<Record<string, string>> = {
  yt: 'youtube',
  tt: 'tiktok',
  ig: 'instagram',
  fb: 'facebook',
};

/** Slugs no team may take: the bio links and the promo link's own prefix.
 *  The site's real top-level routes are read from src/app by the test. */
export const RESERVED_SHORT_SLUGS: readonly string[] = [...Object.keys(BIO_LINKS), 'p'];

export type ShortLinkRoutes = Readonly<Record<string, string>>;

/** Every team short link and the page it stands for. */
export function shortLinkRoutes(): ShortLinkRoutes {
  return bridge.routes;
}

export interface ShortLinkRedirect {
  source: string;
  destination: string;
  permanent: false;
}

/** The team links as redirect rows: one temporary (307) redirect per slug, so
 *  a team that moves pages moves its link with it. The shape next.config
 *  would take; the middleware answers them so the response can carry its
 *  noindex header, which a config redirect cannot. */
export function teamShortRedirects(routes: ShortLinkRoutes = shortLinkRoutes()): ShortLinkRedirect[] {
  return Object.entries(routes).map(([short, destination]) => ({ source: `/${short}`, destination, permanent: false }));
}

/** The bio link's homepage query: utm_source by platform, utm_medium=social,
 *  utm_campaign=bio, over whatever the request carried (ours win). */
export function bioLinkSearch(platform: string, incoming: URLSearchParams = new URLSearchParams()): URLSearchParams {
  const q = new URLSearchParams(incoming);
  q.set('utm_source', platform);
  q.set('utm_medium', 'social');
  q.set('utm_campaign', 'bio');
  return q;
}

export interface ShortLinkHop {
  /** The destination path with its query string. */
  location: string;
  kind: 'team' | 'bio';
}

/** Where a one-segment path hops to, or null when it is not a short link:
 *  a team or school slug to its page with the query carried, a bio slug to
 *  the tagged homepage. Anything with a second segment, an extension or a
 *  character outside the slug alphabet is not ours. */
export function shortLinkRedirect(pathname: string, search: URLSearchParams, routes: ShortLinkRoutes = shortLinkRoutes()): ShortLinkHop | null {
  const m = /^\/([a-z0-9]{2,14})\/?$/.exec(pathname);
  if (!m) return null;
  const slug = m[1];
  const platform = BIO_LINKS[slug];
  if (platform) return { location: `/?${bioLinkSearch(platform, search).toString()}`, kind: 'bio' };
  const destination = Object.prototype.hasOwnProperty.call(routes, slug) ? routes[slug] : undefined;
  if (!destination) return null;
  return { location: withSearch(destination, search), kind: 'team' };
}

/** What the promo lookup needs of an upcoming promo. */
export interface BridgePromo {
  teamId: string;
  promoId: string;
  date: string;
  pageSlug: string;
}

/** The promo a code points at, or null. The whole id (utm_content) wins when
 *  it is among the matches; otherwise a lone prefix match; two promos sharing
 *  a prefix with no whole id to settle it resolve to nothing. */
export function resolvePromoCode<T extends BridgePromo>(code: string, wholeId: string | null | undefined, upcoming: readonly T[]): T | null {
  if (!PROMO_CODE_RE.test(code)) return null;
  const prefix = code.toLowerCase();
  const matches = upcoming.filter((p) => p.promoId.toLowerCase().startsWith(prefix));
  if (matches.length === 0) return null;
  const whole = typeof wholeId === 'string' && PROMO_ID_RE.test(wholeId) ? wholeId.toLowerCase() : null;
  const exact = whole === null ? [] : matches.filter((p) => p.promoId.toLowerCase() === whole);
  const pool = exact.length > 0 ? exact : matches;
  if (pool.length > 1) return null;
  return pool[0];
}

/** `path` with the request's query string (the UTMs) carried over. */
export function withSearch(path: string, search: URLSearchParams): string {
  return withQuery(path, search);
}
